#!/usr/bin/env python3
"""Train the LSTM sign-language classifier with advanced training control.

Training pipeline (strictly anti-data leakage):
  1. Load raw data (hand-collected only — data/ must NOT contain copies
     generated by scripts/add_noise.py; all diversity is created in-memory
     by augment_train_data() AFTER the split, so no near-duplicate can leak
     across train/val/test)
  2. Split raw samples 3-way: held-out test (cfg.TEST_SPLIT) first, then
     train/val on the remainder (cfg.VAL_SPLIT of the total)
  3. Augment ONLY training data (validation data kept pristine)
  4. Compute feature stats ONLY on training data with 0.0 preservation
  5. Standardize train and val with train stats
  6. Train with:
     - Cosine Annealing LR with warmup (stable start, smooth decay)
     - Per-epoch dashboard (loss, accuracy, LR, overfitting gap)
     - Smart early stopping (active after warmup epoch, restores best weights)
     - ModelCheckpoint (saves best model by val_loss)
     - TensorBoard logging
  7. Reload best saved checkpoint from disk
  8. Final evaluation: val report is a tuning signal only (optimistic because
     the checkpoint was selected on val); the held-out test accuracy +
     confusion matrix is the headline result.
  9. Write models/train_record.json beside the checkpoint (hyperparameters,
     per-epoch history, final metrics). The next backup copies that file
     with the model, so each saved model keeps the run that produced it.
"""

import sys, os
