def _build_train_record(
    *, monitor, stopper, class_weights, actual_epochs, n_params, batch_size,
    n_train_raw, n_train_aug, n_val, n_test, seq_len, n_features,
    train_aug_loss, train_aug_acc, train_loss, train_acc,
    val_loss, val_acc, test_loss, test_acc,
    y_val_true, y_val_pred, y_test_true, y_test_pred, val_max_probs,
):
    """Hyperparameters, per-epoch history, and final metrics for this model."""
    actions = [str(a) for a in cfg.ACTIONS]
    label_ids = list(range(len(actions)))
    named_weights = {}
    for cls, w in class_weights.items():
        idx = int(cls)
        name = actions[idx] if idx < len(actions) else f"class_{idx}"
        named_weights[name] = float(w)
    h = monitor.history
    best_loss = float(monitor.best_val_loss)
    return {
        "timestamp": datetime.now().isoformat(timespec="seconds"),
        "keras_version": keras.__version__,
        "model_file": cfg.MODEL_FILENAME,
        "evaluated_weights": "best val_loss checkpoint",
        "actions": actions,
        "n_params": int(n_params),
        "dataset": {
            "train_raw": int(n_train_raw),
            "train_augmented": int(n_train_aug),
            "val": int(n_val),
            "test": int(n_test),
            "sequence_len": int(seq_len),
            "n_features": int(n_features),
            "batch_size": int(batch_size),
        },
        "class_weights": named_weights,
        "hyperparameters": _training_hyperparams(),
        "training": {
            "epochs_ran": int(actual_epochs),
            "epochs_max": int(cfg.EPOCHS),
            "stop_reason": stopper.stop_reason or "Chạy hết số epoch",
            "best_val_loss": best_loss if np.isfinite(best_loss) else None,
            "best_val_loss_epoch": int(monitor.best_val_loss_epoch),
            "best_val_acc": float(monitor.best_val_acc),
            "best_val_acc_epoch": int(monitor.best_val_acc_epoch),
        },
        "history": {
            "epoch": list(range(1, len(h["loss"]) + 1)),
            "loss": h["loss"],
            "acc": h["acc"],
            "val_loss": h["val_loss"],
            "val_acc": h["val_acc"],
            "lr": h["lr"],
            "overfit_gap": h["overfit_gap"],
        },
        "final": {
            "train_aug_loss": float(train_aug_loss),
            "train_aug_acc": float(train_aug_acc),
            "train_loss": float(train_loss),
            "train_acc": float(train_acc),
            "val_loss": float(val_loss),
            "val_acc": float(val_acc),
            "test_loss": float(test_loss),
            "test_acc": float(test_acc),
            "gap_clean_train_minus_val": float(train_acc - val_acc),
            "val_confidence": {
                "mean": float(np.mean(val_max_probs)),
                "min": float(np.min(val_max_probs)),
                "max": float(np.max(val_max_probs)),
                "below_0_7": int(np.sum(np.asarray(val_max_probs) < 0.7)),
            },
        },
        "val_report": classification_report(
            y_val_true, y_val_pred, labels=label_ids, target_names=actions,
            output_dict=True, zero_division=0,
        ),
        "test_report": classification_report(
            y_test_true, y_test_pred, labels=label_ids, target_names=actions,
            output_dict=True, zero_division=0,
        ),
        "val_confusion": confusion_matrix(y_val_true, y_val_pred, labels=label_ids),
        "test_confusion": confusion_matrix(y_test_true, y_test_pred, labels=label_ids),
    }


def _save_train_record(**kwargs):
    """Write models/train_record.json for the checkpoint just trained."""
    record = _jsonify(_build_train_record(**kwargs))
    path = os.path.join(cfg.MODELS_DIR, cfg.TRAIN_RECORD_FILENAME)
    os.makedirs(cfg.MODELS_DIR, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(record, f, indent=2, ensure_ascii=False)
        f.write("\n")
    return path


def main():
    print("=" * 60)
    print("  VSL Translator — Training Pipeline")
    print("=" * 60)

    # ── Backup old model ─────────────────────────────────────────────────────
    _backup_old_model()

    # ── Load data (Strictly anti-leakage: raw -> split -> augment train only) ─
    X_raw, y_raw = load_raw_dataset()
    y_int = y_raw.argmax(axis=1)

    # Held-out test set first (never augmented, never used for early stopping)
    X_rest, X_test_raw, y_rest, y_test = train_test_split(
        X_raw, y_raw, test_size=cfg.TEST_SPLIT, random_state=cfg.RANDOM_SEED,
        stratify=y_int
    )
    # Then train/val split on the remainder
    val_frac = cfg.VAL_SPLIT / (1.0 - cfg.TEST_SPLIT)
    X_train_raw, X_val_raw, y_train_raw, y_val = train_test_split(
        X_rest, y_rest, test_size=val_frac, random_state=cfg.RANDOM_SEED,
        stratify=y_rest.argmax(axis=1)
    )

    # Persist the test indices (as keypoint hashes are unstable) by saving raw test set
    os.makedirs(cfg.MODELS_DIR, exist_ok=True)
    np.savez(os.path.join(cfg.MODELS_DIR, "test_set.npz"), X=X_test_raw, y=y_test)
    print(f"  Held-out test set saved ({len(X_test_raw)} samples, untouched by training)")

    # Augment ONLY training data (validation data remains pristine)
    X_train_aug, y_train = augment_train_data(
        X_train_raw, y_train_raw, augment_factor=cfg.AUGMENT_FACTOR
    )

    # Standardize: calculate stats ONLY on X_train (with 0.0 preservation)
    X_train, feat_mean, feat_std = standardize_features(X_train_aug)

    # Save feature stats for inference
    stats_path = os.path.join(cfg.MODELS_DIR, "feature_stats.npz")
    os.makedirs(cfg.MODELS_DIR, exist_ok=True)
    np.savez(stats_path, mean=feat_mean, std=feat_std)
    print(f"  Feature stats saved to {stats_path} (from train set only)")

    # Standardize validation set using train stats (with 0.0 preservation)
    X_val, _, _ = standardize_features(X_val_raw, mean=feat_mean, std=feat_std)

    n_train, n_val = X_train.shape[0], X_val.shape[0]
    n_classes = len(cfg.ACTIONS)
    batch_size = min(cfg.BATCH_SIZE, n_train)

    print(f"\n  Dataset (No Leakage):")
    print(f"    Train raw : {len(X_train_raw)} samples → {n_train} augmented")
    print(f"    Val raw   : {n_val} samples (unaugmented, strictly separated)")
    print(f"    Classes   : {n_classes} ({', '.join(cfg.ACTIONS)})")
    print(f"    Shape     : {X_train.shape[1:]}")
    print(f"    Batch     : {batch_size}")

    # ── Class weights ────────────────────────────────────────────────────────
    class_weights = _compute_class_weights(y_train)

    os.makedirs(cfg.LOGS_DIR, exist_ok=True)
    os.makedirs(cfg.MODELS_DIR, exist_ok=True)

    # ── Build model ──────────────────────────────────────────────────────────
    model = build_model(n_actions=n_classes, sequence_len=cfg.SEQUENCE_LEN)

    total_params = model.count_params()
    print(f"\n  Model: {total_params:,} parameters")
    print(f"  LR schedule: warmup {cfg.LR_WARMUP_EPOCHS} epochs → "
          f"cosine anneal {cfg.LR_INITIAL:.0e} → {cfg.LR_MIN:.0e}")
    print(f"  Early stop: patience={cfg.ES_PATIENCE}, start_epoch={cfg.ES_START_EPOCH}, "
          f"target_acc={cfg.TARGET_VAL_ACC}, target_loss={cfg.TARGET_VAL_LOSS}")
    print(f"  Overfitting gap threshold: {cfg.OVERFIT_GAP_THRESHOLD}")

    # ── Callbacks ────────────────────────────────────────────────────────────
    monitor = TrainingMonitor(
        overfit_gap_threshold=cfg.OVERFIT_GAP_THRESHOLD,
    )
    stopper = SmartEarlyStopping(
        patience=cfg.ES_PATIENCE,
        min_delta=cfg.ES_MIN_DELTA,
        target_acc=cfg.TARGET_VAL_ACC,
        target_loss=cfg.TARGET_VAL_LOSS,
        overfit_gap_threshold=cfg.OVERFIT_GAP_THRESHOLD,
        overfit_patience=cfg.OVERFIT_PATIENCE,
        start_from_epoch=cfg.ES_START_EPOCH,
        loss_spike_patience=cfg.ES_LOSS_SPIKE_PATIENCE,
        plateau_patience=cfg.ES_PLATEAU_PATIENCE,
        plateau_min_delta=cfg.ES_PLATEAU_MIN_DELTA,
    )
    callbacks = [
        # 1. LR Schedule: warmup + cosine annealing (sole LR controller)
        CosineAnnealingWarmup(
            lr_max=cfg.LR_INITIAL,
            lr_min=cfg.LR_MIN,
            warmup_epochs=cfg.LR_WARMUP_EPOCHS,
            total_epochs=cfg.EPOCHS,
        ),

        # 2. Per-epoch monitoring dashboard
        monitor,

        # 3. Smart multi-criteria early stopping (starts after warmup)
        stopper,

        # 4. Save best model by val_loss
        ModelCheckpoint(
            os.path.join(cfg.MODELS_DIR, cfg.MODEL_FILENAME),
            monitor='val_loss',
            mode='min',
            save_best_only=True,
            verbose=0,  # TrainingMonitor handles logging
        ),

        # 5. TensorBoard
        TensorBoard(log_dir=cfg.LOGS_DIR, histogram_freq=0),
    ]

    # ── Train ────────────────────────────────────────────────────────────────
    print(f"\n  Bắt đầu training ({cfg.EPOCHS} epochs tối đa)...")

    history = model.fit(
        X_train,
        y_train,
        validation_data=(X_val, y_val),
        epochs=cfg.EPOCHS,
        batch_size=batch_size,
        shuffle=True,
        class_weight=class_weights,
        callbacks=callbacks,
        verbose=0,  # suppress default Keras output, TrainingMonitor handles it
    )

    actual_epochs = len(history.history['loss'])

    # ── Final Evaluation ─────────────────────────────────────────────────────
    print("=" * 60)
    print("  Kết quả cuối cùng")
    print("=" * 60)

    model_path = os.path.join(cfg.MODELS_DIR, cfg.MODEL_FILENAME)
    if os.path.exists(model_path):
        print(f"  🔄 Nạp lại checkpoint tốt nhất từ {model_path} để đánh giá...")
        model.load_weights(model_path)

    val_loss, val_acc = model.evaluate(X_val, y_val, verbose=0)
    train_aug_loss, train_aug_acc = model.evaluate(X_train, y_train, verbose=0)
    # Clean-train metric: raw train samples standardized with train stats —
    # this gap (train_clean - val) reflects real generalization, while the
    # augmented-train score only shows fit on perturbed copies.
    X_train_clean, _, _ = standardize_features(
        X_train_raw, mean=feat_mean, std=feat_std)
    train_loss, train_acc = model.evaluate(
        X_train_clean, y_train_raw, verbose=0)

    print(f"\n  Train-aug Loss: {train_aug_loss:.6f}  Train-aug Acc : {train_aug_acc:.4f} (fit on perturbed copies)")
    print(f"  Train Loss : {train_loss:.6f}    Train Acc : {train_acc:.4f} (clean raw train)")
    print(f"  Val Loss   : {val_loss:.6f}    Val Acc   : {val_acc:.4f} (tuning signal — optimistic, checkpoint was selected on val)")
    print(f"  Gap        : {train_acc - val_acc:+.4f} (clean train minus val)")
    print(f"  Epochs     : {actual_epochs}/{cfg.EPOCHS}")

    # Per-class report
    y_pred = model.predict(X_val, verbose=0)
    y_true_labels = np.argmax(y_val, axis=1)
    y_pred_labels = np.argmax(y_pred, axis=1)

    print(f"\n  Classification Report:")
    print(classification_report(
        y_true_labels, y_pred_labels,
        target_names=list(cfg.ACTIONS),
        digits=4,
    ))

    _print_confusion_matrix(y_true_labels, y_pred_labels, list(cfg.ACTIONS))

    # ── Held-out test evaluation (unseen during training) ────────────────────
    X_test, _, _ = standardize_features(X_test_raw, mean=feat_mean, std=feat_std)
    test_loss, test_acc = model.evaluate(X_test, y_test, verbose=0)
    y_test_pred = np.argmax(model.predict(X_test, verbose=0), axis=1)
    y_test_true = np.argmax(y_test, axis=1)
    print(f"\n  Held-out Test Loss: {test_loss:.6f}    Test Acc: {test_acc:.4f}  ← headline result (unseen during training)")
    print(classification_report(
        y_test_true, y_test_pred,
        target_names=list(cfg.ACTIONS),
        digits=4,
        zero_division=0,
    ))

    # ── Confidence analysis ──────────────────────────────────────────────────
    max_probs = np.max(y_pred, axis=1)
    print(f"  Confidence Analysis (val set):")
    print(f"    Mean confidence : {max_probs.mean():.4f}")
    print(f"    Min confidence  : {max_probs.min():.4f}")
    print(f"    Max confidence  : {max_probs.max():.4f}")

    low_conf = np.sum(max_probs < 0.7)
    if low_conf > 0:
        print(f"    ⚠️  {low_conf} predictions có confidence < 70%")

    record_path = _save_train_record(
        monitor=monitor,
        stopper=stopper,
        class_weights=class_weights,
        actual_epochs=actual_epochs,
        n_params=total_params,
        batch_size=batch_size,
        n_train_raw=len(X_train_raw),
        n_train_aug=n_train,
        n_val=n_val,
        n_test=len(X_test_raw),
        seq_len=X_train.shape[1],
        n_features=X_train.shape[2],
        train_aug_loss=train_aug_loss,
        train_aug_acc=train_aug_acc,
        train_loss=train_loss,
        train_acc=train_acc,
        val_loss=val_loss,
        val_acc=val_acc,
        test_loss=test_loss,
        test_acc=test_acc,
        y_val_true=y_true_labels,
        y_val_pred=y_pred_labels,
        y_test_true=y_test_true,
        y_test_pred=y_test_pred,
        val_max_probs=max_probs,
    )

    print(f"\n  ✅ Model saved: {model_path}")
    print(f"  ✅ Train record: {record_path}")
    print("=" * 60)


if __name__ == '__main__':
    main()
